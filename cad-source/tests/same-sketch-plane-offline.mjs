import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../src/main.js',import.meta.url),'utf8');
const start=source.indexOf('function sameSketchPlane(a,b){');
const end=source.indexOf('\nfunction sketchPointToFrame(',start);
assert.ok(start>=0&&end>start,'sameSketchPlane implementation missing');
const context={skDot:(a,b)=>a.reduce((sum,v,i)=>sum+v*b[i],0)};
vm.createContext(context);
vm.runInContext(source.slice(start,end)+';this.sameSketchPlane=sameSketchPlane',context,{timeout:1000});
const same=context.sameSketchPlane;
const base={origin:[0,0,0],normal:[0,0,1]};
assert.equal(same(base,{origin:[12,-3,0],normal:[0,0,-1]}),true,'reversed normal');
