assert.equal(same(base,{origin:[0,0,0],normal:[1,0,0]}),false,'perpendicular plane');
assert.equal(same(base,{origin:[0,0,0],normal:[0,0,0]}),false,'zero normal');
assert.equal(same(base,{origin:[NaN,0,0],normal:[0,0,1]}),false,'nonfinite origin');
assert.equal(same(null,base),false,'missing plane');
