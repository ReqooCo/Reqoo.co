import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import init from 'replicad-opencascadejs';
import * as R from 'replicad';
import {buildModel} from '../src/engine.js';
const req=createRequire(import.meta.url);R.setOC(await init({locateFile:()=>req.resolve('replicad-opencascadejs/wasm')}));
const doc=features=>({format:'reqoo-cad',version:1,title:'Sketch QA',features}),f=(id,type,params,inputs=[])=>({id,type,params,inputs});
const near=(a,b,eps=.02)=>assert.ok(Math.abs(a-b)<eps,`${a} != ${b}`);
let features=[f('line','sketch',{shape:'polyline',points:[[0,0],[20,0],[20,10]],closed:false,plane:'XY',x:0,y:0})];
let m=await buildModel(doc([...features,f('offset','sketchOffset',{distance:2,mode:'Chain',keepInputs:true},['line'])]));
let derived=m.items.find(i=>i.id==='offset');
assert.ok(derived&&derived.kind==='sketch'&&!derived.profileClosed,'Chain offset produces an actual open BREP sketch');
near(derived.bounds[0][1],2);near(derived.bounds[1][0],18);
m.release();
m=await buildModel(doc([...features,f('single','sketchOffset',{distance:3,mode:'Single',edgeIndex:1,keepInputs:true},['line'])]));
derived=m.items.find(i=>i.id==='single');
assert.ok(derived&&!derived.profileClosed);
near(derived.bounds[0][0],17);near(derived.bounds[1][1],10);
m.release();
features=[f('block','box',{width:20,depth:10,height:8})];
m=await buildModel(doc(features));
const top=m.items.find(i=>i.id==='block').faceInfo.find(v=>v.type==='PLANE'&&v.normal[2]>.99);
assert.ok(top,'Test block needs planar top face');m.release();
features.push(f('projection','faceSketch',{distance:0,face:top.index,faceRef:top.reference},['block']));
m=await buildModel(doc(features));
derived=m.items.find(i=>i.id==='projection');
assert.ok(derived&&derived.kind==='sketch'&&derived.profileClosed,'Face projection yields closed native sketch');
near(derived.area,200);
m.release();
features[0].params.width=24; // linked profile regenerates with upstream parent
m=await buildModel(doc(features));
near(m.items.find(i=>i.id==='projection').area,240);
m.release();
console.log('SKETCH NATIVE PARITY PASS: open chain, selected single edge, analytic face→linked sketch and upstream width regeneration');
