import assert from 'node:assert/strict';
import {geometryPoints,trimSketchSegment,offsetSketchPolyline,sketchSegments} from '../src/sketch-edit-geometry.js';
const near=(a,b)=>assert.ok(Math.abs(a-b)<1e-6, `${a} != ${b}`);
const line={shape:'polyline',points:[[0,0],[20,0]],closed:false};
const clip={shape:'rectangle',x:10,y:0,width:8,height:10};
const cut=trimSketchSegment(line,[10,0],[clip],.1);
assert.equal(cut.parts.length,2);assert.deepEqual(cut.parts[0].points,[[0,0],[6,0]]);assert.deepEqual(cut.parts[1].points,[[14,0],[20,0]]);
assert.deepEqual(line.points,[[0,0],[20,0]],'Source feature must stay immutable');
const circle={shape:'circle',x:10,y:0,radius:3};
const arc=trimSketchSegment(line,[10,0],[circle],.1);
assert.deepEqual(arc.parts[0].points,[[0,0],[7,0]]);
assert.deepEqual(arc.parts[1].points,[[13,0],[20,0]]);
const ellipse={shape:'ellipse',x:10,y:0,width:8,height:4};
const ellipseCut=trimSketchSegment(line,[10,0],[ellipse],.1);
near(ellipseCut.parts[0].points.at(-1)[0],6);near(ellipseCut.parts[1].points[0][0],14);
const rect={shape:'rectangle',x:10,y:0,width:20,height:10};
const rectCut=trimSketchSegment(rect,[0,0],[],.1);
assert.equal(rectCut.parts.length,1);
assert.equal(rectCut.parts[0].closed,false);
assert.equal(rectCut.parts[0].points.length,4,'Removing one rectangle edge leaves three exact connected edges');
const off=offsetSketchPolyline(line,2);
assert.deepEqual(off.points,[[0,2],[20,2]]);
const elbow={shape:'polyline',points:[[0,0],[10,0],[10,10]],closed:false};
const miter=offsetSketchPolyline(elbow,2);
assert.deepEqual(miter.points,[[0,2],[8,2],[8,10]]);
const only=offsetSketchPolyline(elbow,-3,{mode:'Single',edgeIndex:1});
assert.deepEqual(only.points,[[13,0],[13,10]]);
assert.equal(sketchSegments(circle).length,1);
assert.throws(()=>offsetSketchPolyline(line,0),/non-zero/);
assert.throws(()=>offsetSketchPolyline(rect,2),/native CAD sketch kernel/);
assert.throws(()=>trimSketchSegment(line,[10,30],[clip],1),/Tap directly/);
assert.throws(()=>trimSketchSegment({...line,operations:[{type:'offset',distance:2}]},[10,0],[],1),/original sketch/);
console.log('SKETCH EDIT GEOMETRY PASS: trim between rectangle/circle/ellipse boundaries, native line accuracy, open/closed trim, single/chain offset and input immutability');
const diameter={shape:'polyline',points:[[-20,0],[20,0]],closed:false};
const round={shape:'circle',radius:10,x:0,y:0};
const half=trimSketchSegment(round,[0,10],[diameter],.01);
assert.equal(half.parts[0].shape,'arc');
assert.ok(Math.abs(half.parts[0].sagitta-10)<1e-7);
assert.equal(half.parts[0].closed,false);
const quarter=trimSketchSegment(half.parts[0],[7,-7],[{shape:'polyline',points:[[0,-20],[0,20]],closed:false}],.2);
assert.equal(quarter.parts.length,1);
assert.ok(quarter.parts[0].sagitta>0&&quarter.parts[0].sagitta<10);
const crossingCircles=trimSketchSegment(round,[10,0],[{shape:'circle',radius:10,x:10,y:0}],.01);
assert.equal(crossingCircles.parts.length,1);
assert.ok(crossingCircles.parts[0].sagitta>10,'Major circular remainder retained');
assert.throws(()=>trimSketchSegment(round,[10,0],[round],.01),/Coincident/);
assert.throws(()=>trimSketchSegment(round,[10,0],[{shape:'ellipse',width:10,height:20}],.01),/not supported/);
assert.deepEqual(trimSketchSegment(round,[10,0],[],.01).parts,[]);
assert.equal(round.shape,'circle');
console.log('CIRCULAR TRIM PASS: half/quarter/major arcs, repeated Trim, coincidence and unsupported boundary safety');
assert.equal(trimSketchSegment({shape:'polyline',points:[[-20,5],[20,5]],closed:false},[0,5],[half.parts[0]],.01).parts.length,0,'Finite arc must not cut a line on its missing half');
assert.equal(trimSketchSegment({shape:'polyline',points:[[-20,-5],[20,-5]],closed:false},[0,-5],[half.parts[0]],.01).parts.length,2,'Finite arc cuts a line on its retained half');
